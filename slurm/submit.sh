#!/bin/bash
# shape2delta submitter. Does NO work itself — only writes a per-submission
# env-file and calls sbatch, passing the env-file PATH as a positional arg.
# NEVER uses --export (that triggers user-env retrieval -> requeued+held on this
# cluster). Config travels as a sourced file; list-valued vars are safe in a file.
#
# usage:
#   slurm/submit.sh <job.sbatch> [afterok_jobid[:jobid...]] [KEY=VALUE ...]
# examples:
#   slurm/submit.sh e0_coverage.sbatch
#   slurm/submit.sh e3_ablation.sbatch 123456 ATLAS=sciplex3 TIER=T2
set -euo pipefail
ROOT=/zfsauton2/home/yixiz/shape2delta
cd "$ROOT"

usage(){ echo "usage: $0 <job.sbatch> [afterok_jobid] [KEY=VALUE ...]" >&2; exit 2; }
[ $# -ge 1 ] || usage
JOB="$1"; shift

DEP=""
if [ $# -ge 1 ] && [[ "$1" =~ ^[0-9]+(:[0-9]+)*$ ]]; then
  DEP="--dependency=afterok:$1"; shift
fi

mkdir -p "$ROOT/configs"
STAMP=$(date +%Y%m%d_%H%M%S)
ENVFILE="$ROOT/configs/env_${STAMP}_$$.sh"
{
  echo "# autogenerated $(date -Is) by submit.sh for $JOB"
  for kv in "$@"; do
    key="${kv%%=*}"; val="${kv#*=}"
    printf 'export %s=%q\n' "$key" "$val"
  done
} > "$ENVFILE"

# scrub SLURM_* from our own env so sbatch won't set SLURM_GET_USER_ENV
for v in $(compgen -v | grep '^SLURM_' || true); do unset "$v" || true; done

JOBPATH="$ROOT/slurm/$JOB"
[ -f "$JOBPATH" ] || JOBPATH="$JOB"
[ -f "$JOBPATH" ] || { echo "no such job script: $JOB" >&2; exit 2; }

echo "[submit] job=$JOBPATH dep=${DEP:-none} envfile=$ENVFILE"
echo "[submit] env-file contents:"; sed 's/^/           /' "$ENVFILE"
set -x
sbatch $DEP "$JOBPATH" "$ENVFILE"
